"""Build the full results table (one row per document and tool) from
the results files and put it into section 3 of docs/report.md.

Sources: results/runs.csv (times, median of repeats), facts.csv,
table_scores.csv, reading_order.csv and manual_checks.csv (Day 1
by-eye ratings).
Usage: python scripts/make_results_table.py
"""
import csv
import statistics
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RES = ROOT / "results"
REPORT = ROOT / "docs" / "report.md"
OUT = RES / "results_table.md"
START = "<!-- RESULTS START -->"
END = "<!-- RESULTS END -->"
OLD_HEADER = "|Document|Tool|"
TOOLS = ["markitdown", "pymupdf4llm", "docling"]


def read_csv(name):
    """Read a CSV, skipping blank lines and PowerShell leftovers."""
    with open(RES / name, encoding="utf-8-sig", newline="") as f:
        lines = [x for x in f.read().splitlines()
                 if x.strip() and not x.startswith(("@'", "'@"))]
    return list(csv.DictReader(lines))


def num(x):
    try:
        return float(x)
    except (TypeError, ValueError):
        return None


def med(rows, col):
    xs = [num(r[col]) for r in rows if num(r[col]) is not None]
    return statistics.median(xs) if xs else None


def fmt(x, digits=2):
    if x is None:
        return ""
    return ("{:." + str(digits) + "f}").format(x)


summary = read_csv("summary.csv")
runs = read_csv("runs.csv")
facts = {(r["tool"], r["file"]): r for r in read_csv("facts.csv")}
order = {(r["tool"], r["file"]): r for r in read_csv("reading_order.csv")}
manual = {(r["tool"], r["file"]): r for r in read_csv("manual_checks.csv")}
tables = {}
for r in read_csv("table_scores.csv"):
    k = (r["tool"], r["file"])
    ok, n = tables.get(k, (0, 0))
    tables[k] = (ok + int(r["cells_ok"]), n + int(r["cells_total"]))


def facts_text(k):
    r = facts.get(k)
    if not r:
        return ""
    return r["found"] + "/" + r["total"] + " (" + r["percent"] + "%)"


def cells_text(k):
    if k not in tables:
        return "n/a"
    ok, n = tables[k]
    return "{}/{} ({:.0f}%)".format(ok, n, 100 * ok / n)


def order_text(k):
    r = order.get(k)
    if not r:
        return ""
    if r["order_ok"] == "FAIL":
        return "FAIL: " + r["out_of_order"]
    return r["order_ok"]


def sort_key(r):
    t = TOOLS.index(r["tool"]) if r["tool"] in TOOLS else 9
    return (r["file"], t)


header = ["Document", "Tool", "Status", "Model load (s)",
          "First run (s)", "Warm run (s)", "Peak RAM (MB)",
          "Facts found", "Table cells (auto)", "Reading order (auto)",
          "Table intact (by eye)", "Reading order (by eye)"]
lines = ["|" + "|".join(header) + "|",
         "|" + "|".join(["-"] * len(header)) + "|"]
for s in sorted(summary, key=sort_key):
    k = (s["tool"], s["file"])
    if s["status"] != "ok":
        cells = [s["file"], s["tool"], s["status"]] + [""] * 9
    else:
        ok_runs = [r for r in runs if (r["tool"], r["file"]) == k
                   and r["status"] == "ok"]
        m = manual.get(k, {})
        cells = [s["file"], s["tool"], "ok",
                 fmt(med(ok_runs, "load_s")),
                 fmt(med(ok_runs, "first_s"), 3),
                 fmt(med(ok_runs, "warm_s"), 3),
                 fmt(med(ok_runs, "peak_mb"), 0),
                 facts_text(k), cells_text(k), order_text(k),
                 m.get("table_intact", "?"),
                 m.get("reading_order", "?")]
    lines.append("|" + "|".join(cells) + "|")

legend = ("Generated by scripts/make_results_table.py. Do not edit by"
          " hand. [measured] Times: median of the repeats in"
          " results/runs.csv. Facts: results/facts.csv. Table cells:"
          " cell-by-cell against data/expected_tables"
          " (scripts/score_tables.py; for 05_sheet.xlsx both sheets"
          " are added together). Reading order: scripts/reading_order.py"
          " (FAIL names the out-of-order fact). By-eye columns: Day 1"
          " manual ratings in results/manual_checks.csv. n/a = the"
          " document has no table.")
block = [START, ""] + lines + ["", legend, END]

OUT.write_text("\n".join(block[1:-1]) + "\n", encoding="utf-8")
t = REPORT.read_bytes().decode("utf-8")
nl = "\r\n" if "\r\n" in t else "\n"
text = nl.join(block)
if START in t and END in t:
    a = t.index(START)
    b = t.index(END) + len(END)
    t = t[:a] + text + t[b:]
else:
    i = t.find(nl + OLD_HEADER)
    if i < 0:
        raise SystemExit("ERROR: old results table not found,"
                         " nothing changed")
    i += len(nl)
    j = i
    while j < len(t) and t.startswith("|", j):
        e = t.find(nl, j)
        j = len(t) if e < 0 else e + len(nl)
    t = t[:i] + text + nl + t[j:]
REPORT.write_bytes(t.encode("utf-8"))
print("\n".join(lines[:6]))
print("... (" + str(len(lines) - 2) + " rows in total)")
print("Updated docs/report.md section 3 and wrote results/results_table.md")